-- Goal Guide BD: Contact Us page settings and private Admin message inbox.
-- Run this in the Supabase SQL Editor for the project's existing public anon key.
-- Create trusted inbox users in Supabase Dashboard > Authentication > Users.

create table if not exists public.contact_page_settings (
  id integer primary key,
  content jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  constraint contact_page_settings_singleton_id check (id = 1)
);

alter table public.contact_page_settings enable row level security;
grant select, insert, update on public.contact_page_settings to anon, authenticated;

drop policy if exists "Public can read contact page settings" on public.contact_page_settings;
create policy "Public can read contact page settings"
  on public.contact_page_settings for select to anon, authenticated
  using (id = 1);

drop policy if exists "Admin client can insert contact page settings" on public.contact_page_settings;
create policy "Admin client can insert contact page settings"
  on public.contact_page_settings for insert to anon, authenticated
  with check (id = 1);

drop policy if exists "Admin client can update contact page settings" on public.contact_page_settings;
create policy "Admin client can update contact page settings"
  on public.contact_page_settings for update to anon, authenticated
  using (id = 1)
  with check (id = 1);

