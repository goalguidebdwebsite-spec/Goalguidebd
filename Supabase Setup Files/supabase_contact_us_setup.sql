create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  email text not null check (char_length(email) between 3 and 254),
  phone text not null check (char_length(phone) between 1 and 40),
  message text not null check (char_length(message) between 1 and 5000),
  created_at timestamptz not null default now()
);

create index if not exists contact_messages_created_at_idx
  on public.contact_messages (created_at desc);

alter table public.contact_messages enable row level security;
grant insert on public.contact_messages to anon, authenticated;
grant select, delete on public.contact_messages to authenticated;
grant usage, select on sequence public.contact_messages_id_seq to anon, authenticated;

drop policy if exists "Visitors can submit contact messages" on public.contact_messages;
create policy "Visitors can submit contact messages"
  on public.contact_messages for insert to anon, authenticated
  with check (
    char_length(name) between 1 and 120
    and char_length(email) between 3 and 254
    and char_length(phone) between 1 and 40
    and char_length(message) between 1 and 5000
  );

drop policy if exists "Authenticated inbox users can read contact messages" on public.contact_messages;
create policy "Authenticated inbox users can read contact messages"
  on public.contact_messages for select to authenticated
  using (true);

drop policy if exists "Authenticated inbox users can delete contact messages" on public.contact_messages;
create policy "Authenticated inbox users can delete contact messages"
  on public.contact_messages for delete to authenticated
  using (true);
